# LOGIC
# 1. Initialize a variable with the value 1.
# 2. Check whether the variable is less than or equal to 3.
# 3. If the condition is true, print the variable's value.
# 4. Increment the variable by 1.
# 5. Repeat until the condition becomes false.

# CODE
i = 1

while i <= 3:
    print(i)
    i += 1
